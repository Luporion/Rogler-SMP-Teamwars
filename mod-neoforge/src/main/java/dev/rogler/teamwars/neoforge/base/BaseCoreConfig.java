package dev.rogler.teamwars.neoforge.base;

import dev.rogler.teamwars.core.BaseZone;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.level.storage.LevelResource;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;

public record BaseCoreConfig(int innerRadius, int outerRadius, int carrySeconds) {
    public static final BaseCoreConfig DEFAULT = new BaseCoreConfig(0, 5000, 3600);
    public BaseCoreConfig {
        new BaseZone(0, 0, innerRadius, outerRadius);
        if (carrySeconds < 60 || carrySeconds > 86400) throw new IllegalArgumentException("carry_seconds must be 60..86400");
    }
    public BaseZone zone(MinecraftServer server) {
        var spawn = server.overworld().getSharedSpawnPos();
        return new BaseZone(spawn.getX(), spawn.getZ(), innerRadius, outerRadius);
    }
    public static BaseCoreConfig load(MinecraftServer server) throws IOException {
        Path path = server.getWorldPath(LevelResource.ROOT).resolve("serverconfig").resolve("roglerteamwars-base.properties");
        if (Files.notExists(path)) {
            Files.createDirectories(path.getParent());
            Properties defaults = new Properties();
            defaults.setProperty("min_radius", "0"); defaults.setProperty("max_radius", "5000");
            defaults.setProperty("carry_seconds", "3600");
            try (OutputStream output = Files.newOutputStream(path)) {
                defaults.store(output, "Rogler TeamWars Base Core v0.2.1; allowed Overworld radius 0-5000 by default");
            }
        }
        // Migrate only a file known to have been generated by v0.2.0 with both original defaults.
        // Customized worlds must not be silently changed. A backup is made before rewriting.
        String rawFile = Files.readString(path);
        Properties values = new Properties();
        try (InputStream input = Files.newInputStream(path)) { values.load(input); }
        if (rawFile.contains("Rogler TeamWars Base Core v0.2.0")
            && "300".equals(values.getProperty("min_radius"))
            && "2000".equals(values.getProperty("max_radius"))) {
            Path backup = path.resolveSibling("roglerteamwars-base.properties.v020.bak");
            if (Files.notExists(backup)) Files.copy(path, backup);
            values.setProperty("min_radius", "0");
            values.setProperty("max_radius", "5000");
            try (OutputStream output = Files.newOutputStream(path)) {
                values.store(output, "Rogler TeamWars Base Core v0.2.1; migrated untouched v0.2.0 radius defaults");
            }
        }
        try {
            return new BaseCoreConfig(Integer.parseInt(values.getProperty("min_radius", "0")),
                Integer.parseInt(values.getProperty("max_radius", "5000")),
                Integer.parseInt(values.getProperty("carry_seconds", "3600")));
        } catch (IllegalArgumentException ex) { throw new IOException("Invalid base config: " + ex.getMessage(), ex); }
    }
}
